const sub = (a, b) => ({ x: a.x - b.x, y: a.y - b.y });
const dot = (a, b) => a.x * b.x + a.y * b.y;

// Sistema di riferimento del volto: origine sulla linea mediana, ux verso il lato sinistro
// del soggetto (destra immagine), uy verso il mento, W = larghezza del viso in pixel.
export function faceFrame(lm) {
  const eyeR = lm[468] || lm[33], eyeL = lm[473] || lm[263];
  const angle = Math.atan2(eyeL.y - eyeR.y, eyeL.x - eyeR.x);
  const ux = { x: Math.cos(angle), y: Math.sin(angle) };
  const uy = { x: -Math.sin(angle), y: Math.cos(angle) };
  let ox = 0, oy = 0;
  for (const i of IDX.midline) { ox += lm[i].x; oy += lm[i].y; }
  const n = IDX.midline.length;
  // L'origine è proiettata sulla retta mediana stimata (media dei punti centrali).
  const origin = { x: ox / n, y: oy / n };
  const W = Math.hypot(lm[234].x - lm[454].x, lm[234].y - lm[454].y);
  const H = Math.hypot(lm[10].x - lm[152].x, lm[10].y - lm[152].y);
  const toLocal = (p) => { const d = sub(p, origin); return { x: dot(d, ux) / W, y: dot(d, uy) / W }; };
  const toImage = (x, y) => ({ x: origin.x + (ux.x * x + uy.x * y) * W, y: origin.y + (ux.y * x + uy.y * y) * W });
  const vec = (x, y) => ({ x: (ux.x * x + uy.x * y) * W, y: (ux.y * x + uy.y * y) * W });
  return { lm, angle, ux, uy, origin, W, H, eyeR, eyeL, toLocal, toImage, vec,
    P: (i) => lm[i], pts: (ids) => ids.map((i) => lm[i]) };
}
